/* Interview camera tracks, recovered from fn_17_7A74 (the per-frame camera step) and
 * fn_17_7728, which read the same records. lbl_17_data_63190 holds 41 sets of 16 track
 * pointers (both index it by set * 64 + kind * 4), one pointer per track declared below; a
 * track is an array of moves stepped by index. A track whose first frame count is -1 is
 * replaced by the default track lbl_17_data_0. */

/* One camera pose, laid out like main_rel's CameraState (camera_get_state_object()):
 * fn_17_7A74 copies eye, target, fov and roll from it into the live camera. */
typedef struct {
    u32 flags;     /* 0x00: zero in every retail move */
    f32 eye[3];    /* 0x04: interpolated into the live camera position */
    f32 target[3]; /* 0x10: interpolated into the live look-at point */
    f32 fov;       /* 0x1C */
    s16 roll;      /* 0x20 */
} InterviewCameraKey;

/* One move from pose "from" to pose "to". fn_17_7A74 switches on mode:
 * 0 = linear over the move's frames, 3 = ease in/out, 2 = exponential blend at rate. */
typedef struct {
    s32 frames;               /* 0x00: duration; -1 in a track's first move selects the default track */
    f32 rate;                 /* 0x04: blend factor used by mode 2 */
    InterviewCameraKey from;  /* 0x08 */
    InterviewCameraKey to;    /* 0x2C */
    s16 mode;                 /* 0x50 */
} InterviewCameraMove;

