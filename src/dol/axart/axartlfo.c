void AXARTLfo(AXART_LFO *lfo) {
    lfo->counter = lfo->counter + lfo->delta;
    if (lfo->counter >= 1.0f) {
        f32 lfoSamples = lfo->counter;

        lfo->counter = lfoSamples - lfoSamples;
        lfo->sampleIndex = lfo->sampleIndex + (u32)lfoSamples;
        lfo->sampleIndex = lfo->sampleIndex % lfo->length;
        lfo->sample1 = lfo->sample;
        lfo->sample = lfo->lfo[lfo->sampleIndex];
    }
    lfo->output = lfo->sample1 - lfo->counter * (lfo->sample1 - lfo->sample);
}
